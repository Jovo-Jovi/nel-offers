import fs from "node:fs";
import path from "node:path";

const ledgerPath = path.join("docs", "usage", "runs.jsonl");
const pagePath = path.join("docs", "usage", "README.md");
const stageOrder = ["blueprint", "reviewer", "builder", "review-gate"];
const taskOrder = ["blueprint", "T01", "T02", "T03", "T04", "go-live"];

function readRuns() {
  if (!fs.existsSync(ledgerPath)) return [];
  const text = fs.readFileSync(ledgerPath, "utf8");
  const runs = [];
  for (const line of text.split(/\r?\n/)) {
    if (line.trim().length === 0) continue;
    runs.push(JSON.parse(line));
  }
  return runs;
}

function formatCount(value) {
  return new Intl.NumberFormat("en-US").format(value);
}

function sum(runs, key) {
  let total = 0;
  for (const run of runs) {
    const value = run[key];
    if (typeof value === "number") total += value;
  }
  return total;
}

function costCell(runs) {
  for (const run of runs) {
    if (typeof run.cost_usd !== "number") return "\u2014";
  }
  return formatCount(sum(runs, "cost_usd"));
}

function cells(runs) {
  return [
    String(runs.length),
    formatCount(sum(runs, "input")),
    formatCount(sum(runs, "output")),
    formatCount(sum(runs, "cache_read")),
    formatCount(sum(runs, "cache_write")),
    costCell(runs),
  ];
}

function markdownTable(header, body) {
  const lines = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`];
  for (const row of body) lines.push(`| ${row.join(" | ")} |`);
  return lines.join("\n");
}

function taskRank(task) {
  const fix = task.match(/-F(\d*)$/);
  const base = fix ? task.slice(0, fix.index) : task;
  const fixRank = fix ? (fix[1] === "" ? 0 : Number(fix[1])) : -1;
  return [taskOrder.indexOf(base), fixRank];
}

function render(runs) {
  let notReported = 0;
  let last = "\u2014";
  for (const run of runs) {
    if (run.source === "not-reported") notReported += 1;
    if (last === "\u2014" || run.run_at > last) last = run.run_at;
  }

  const modelGroups = new Map();
  for (const run of runs) {
    const key = `${run.tool}\t${run.model}`;
    const list = modelGroups.get(key) ?? [];
    list.push(run);
    modelGroups.set(key, list);
  }
  const modelRows = [];
  for (const key of [...modelGroups.keys()].sort((a, b) => a.localeCompare(b))) {
    const [tool, model] = key.split("\t");
    modelRows.push([tool, model, ...cells(modelGroups.get(key))]);
  }

  const stageRows = [];
  for (const stage of stageOrder) {
    const matching = runs.filter((run) => run.stage === stage);
    if (matching.length === 0) continue;
    stageRows.push([stage, ...cells(matching)]);
  }

  const taskNames = [...new Set(runs.map((run) => run.task))];
  taskNames.sort((a, b) => {
    const [aBase, aFix] = taskRank(a);
    const [bBase, bFix] = taskRank(b);
    return aBase - bBase || aFix - bFix || a.localeCompare(b);
  });
  const taskRows = taskNames.map((task) => [
    task,
    ...cells(runs.filter((run) => run.task === task)),
  ]);

  const prose = [
    "# Usage",
    "",
    "Every agent run of this project, totalled from docs/usage/runs.jsonl: one line per run,",
    "appended by npm run usage:record (scripts/usage/record.mjs). Never edit that file by hand.",
    "This page is regenerated by npm run usage:report and is never edited by hand either.",
    "",
    "Tokens are as each tool reported them. Cache read and cache write are kept apart from input.",
    'Cost is the tool\'s own figure where it gives one; otherwise "\u2014". No prices are kept in this',
    "repository; cost is worked out outside it from the token totals.",
    "Reviewer runs are measured from the reviewer's own session records once each answer is",
    "complete.",
    "Not in these totals: any run not recorded in runs.jsonl.",
    "",
    `Runs: ${runs.length} \u00b7 Not reported: ${notReported} \u00b7 Last run: ${last}`,
    "",
    "## Total",
    markdownTable(
      ["Runs", "Input", "Output", "Cache read", "Cache write", "Cost (USD)"],
      [cells(runs)],
    ),
    "",
    "## By model",
    markdownTable(
      ["Tool", "Model", "Runs", "Input", "Output", "Cache read", "Cache write", "Cost (USD)"],
      modelRows,
    ),
    "",
    "## By stage",
    markdownTable(
      ["Stage", "Runs", "Input", "Output", "Cache read", "Cache write", "Cost (USD)"],
      stageRows,
    ),
    "",
    "## By task",
    markdownTable(
      ["Task", "Runs", "Input", "Output", "Cache read", "Cache write", "Cost (USD)"],
      taskRows,
    ),
    "",
  ];
  return prose.join("\n");
}

const rendered = render(readRuns());
if (process.argv.includes("--check")) {
  const actual = fs.existsSync(pagePath) ? fs.readFileSync(pagePath, "utf8") : "";
  if (actual !== rendered) {
    console.error("usage report differs");
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(pagePath), { recursive: true });
  fs.writeFileSync(pagePath, rendered, "utf8");
}
